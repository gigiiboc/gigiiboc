<script>
$(function() {
	$(".js-mobile-menu .js-menu-open").click(function(){
		$(this).closest("li").siblings().find(".js-menu-open").removeClass("on");
		$(this).closest("li").siblings().find("ul").slideUp().removeClass("on");

		if ('block' == $(this).next("ul").css('display')){
			$(this).closest("li").find(".js-menu-open").removeClass("on");
			$(this).closest("li").find("ul").stop().slideUp().removeClass("on");
		}else{
			$(this).addClass("on");
			$(this).next("ul").stop().slideDown().addClass("on");
		}
	})
});
</script>
